export function showToast(message, type = 'info', duration = 3500) {
  let container = document.getElementById('toast-container');
  if (!container) {
    container = document.createElement('div');
    container.id = 'toast-container';
    document.body.appendChild(container);
  }

  const toast = document.createElement('div');
  toast.className = `toast toast-${type}`;
  toast.setAttribute('role', 'alert');

  let icon = ICONS.alertCircle;
  if (type === 'success') icon = ICONS.check;
  if (type === 'error') icon = ICONS.alertCircle;

  toast.innerHTML = `
    <div style="flex-shrink: 0; color: currentColor;">${icon}</div>
    <div style="flex: 1; font-size: 0.875rem; font-weight: 500; color: var(--text-main);">${escapeHtml(message)}</div>
    <button class="btn btn-ghost btn-sm" style="padding: 2px; min-width: auto; color: var(--text-muted);" aria-label="Dismiss toast">
      ${ICONS.x}
    </button>
  `;

  const closeBtn = toast.querySelector('button');
  closeBtn.addEventListener('click', () => toast.remove());

  container.appendChild(toast);

  setTimeout(() => {
    if (toast.parentElement) {
      toast.style.opacity = '0';
      toast.style.transform = 'translateX(100%)';
      toast.style.transition = 'all 200ms ease-in';
      setTimeout(() => toast.remove(), 200);
    }
  }, duration);
}

export function openModal(modalId) {
  const modal = document.getElementById(modalId);
  if (modal) {
    modal.classList.add('active');
    modal.setAttribute('aria-hidden', 'false');
    const firstInput = modal.querySelector('input, button, select');
    if (firstInput) firstInput.focus();
  }
}

export function closeModal(modalId) {
  const modal = document.getElementById(modalId);
  if (modal) {
    modal.classList.remove('active');
    modal.setAttribute('aria-hidden', 'true');
  }
}

export function copyToClipboard(text, successMsg = "Copied to clipboard!") {
  navigator.clipboard.writeText(text).then(() => {
    showToast(successMsg, 'success');
  }).catch(() => {
    showToast("Failed to copy", 'error');
  });
}

export function formatCurrencyINR(amount) {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    minimumFractionDigits: 2
  }).format(amount);
}

export function formatBytes(bytes, decimals = 1) {
  if (!bytes || bytes === 0) return '0 B';
  const k = 1024;
  const dm = decimals < 0 ? 0 : decimals;
  const sizes = ['B', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return parseFloat((bytes / Math.pow(k, i)).toFixed(dm)) + ' ' + sizes[i];
}

export function formatTimeAgo(isoString) {
  const diff = Date.now() - new Date(isoString).getTime();
  const minutes = Math.floor(diff / 60000);
  if (minutes < 1) return 'Just now';
  if (minutes < 60) return `${minutes}m ago`;
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return `${hours}h ago`;
  const days = Math.floor(hours / 24);
  return `${days}d ago`;
}

export function getStatusBadge(status) {
  const labels = {
    pending_confirmation: 'Pending Review',
    approved_awaiting_cash: 'Awaiting Cash',
    payment_confirmed: 'Paid / Queued',
    queued: 'Queued',
    submitted: 'Submitted',
    under_review: 'Under Review',
    printing: 'Printing',
    completed: 'Completed',
    rejected: 'Rejected',
    cancelled: 'Cancelled',
    failed: 'Failed'
  };
  const cssClass = {
    pending_confirmation: 'submitted',
    approved_awaiting_cash: 'under-review',
    payment_confirmed: 'completed',
    queued: 'completed',
    failed: 'rejected'
  }[status] || status;
  return `<span class="badge badge-${cssClass}"><span class="badge-dot"></span>${labels[status] || status}</span>`;
}

export function escapeHtml(str) {
  if (!str) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}
